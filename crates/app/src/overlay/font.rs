/// What a character outside printable ASCII draws as: a hollow box.
pub(crate) const UNKNOWN: Glyph = [
    0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111,
];

/// Every glyph of [`ART`] as bit rows.
#[expect(
    clippy::indexing_slicing,
    reason = "evaluated at compile time: an index out of bounds fails the build, never a run"
)]
const GLYPHS: [Glyph; COUNT] = {
    let mut glyphs = [[0; HEIGHT]; COUNT];
    let mut index = 0;
    while index < COUNT {
        let mut row = 0;
        while row < HEIGHT {
            glyphs[index][row] = bits(ART[index][row]);
            row += 1;
        }
        index += 1;
    }
    glyphs
};

/// One row of pixel art as bits, the leftmost pixel highest: `#` is ink, anything else blank.
/// Only the first [`WIDTH`] characters count.
const fn bits(row: &str) -> u8 {
    let mut bits = 0;
    let mut rest = row.as_bytes();
    let mut column = 0;
    while let [first, tail @ ..] = rest
        && column < WIDTH
    {
        bits <<= 1;
        if *first == b'#' {
            bits |= 1;
        }
        rest = tail;
        column += 1;
    }
    bits << (WIDTH - column)
}

/// The glyph `c` draws as: its own for printable ASCII, else [`UNKNOWN`].
pub(crate) fn glyph(c: char) -> Glyph {
    u8::try_from(c)
        .ok()
        .and_then(|byte| byte.checked_sub(FIRST))
        .and_then(|index| GLYPHS.get(usize::from(index)))
        .copied()
        .unwrap_or(UNKNOWN)
}

#[cfg(test)]
#[expect(clippy::missing_panics_doc, reason = "tests panic to fail")]
mod tests {
    use std::collections::BTreeMap;

    use super::*;

    #[test]
    fn every_row_of_the_art_is_five_pixels_of_ink_or_blank() {
        let rows = ART.iter().flatten();
        for row in rows {
            assert_eq!(row.len(), WIDTH, "{row:?}");
            assert!(row.chars().all(|c| c == '#' || c == '.'), "{row:?}");
        }
    }

    #[test]
    fn bits_put_the_leftmost_pixel_highest() {
        assert_eq!(bits("#...."), 0b10000);
        assert_eq!(bits("....#"), 0b00001);
        assert_eq!(bits(".#.#."), 0b01010);
        assert_eq!(bits("#"), 0b10000, "a short row is blank to the right");
    }

    #[test]
    fn space_is_blank_and_every_other_character_has_ink_and_its_own_glyph() {
        assert_eq!(glyph(' '), [0; HEIGHT]);
        let mut seen: BTreeMap<Glyph, char> = BTreeMap::new();
        let printable = (b'!'..=b'~').map(char::from);
        for c in printable {
            let g = glyph(c);
            assert!(g.iter().any(|&row| row != 0), "{c:?} has ink");
            assert!(
                g.iter().all(|&row| row < 1 << WIDTH),
                "{c:?} fits five pixels"
            );
            if let Some(other) = seen.insert(g, c) {
                panic!("{c:?} draws the same as {other:?}");
            }
        }
        assert_eq!(seen.len(), COUNT - 1);
    }

    #[test]
    fn characters_outside_printable_ascii_draw_as_a_box() {
        for c in ['\n', '\u{7F}', 'é', '×'] {
            assert_eq!(glyph(c), UNKNOWN, "{c:?}");
        }
        assert_ne!(glyph('A'), UNKNOWN);
    }
}
